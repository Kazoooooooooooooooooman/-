"""売り手の例: 日本語のQ&Aデータを出品する。

大事なのは最初の3行だけ。あとは「データを1件ずつ送り続ける」くり返しです。
実際に売るときは、SAMPLES を自分で作ったオリジナルのデータに置き換えてください。
"""

import time

import adp

s = adp.connect("adp_live_kaz_ja", schema="ja_qa.v1")  # 自分のキーとデータの種類

SAMPLES = [
    {"q": "「お疲れ様です」と「ご苦労様です」の違いは？", "a": "「ご苦労様です」は目上から目下へのねぎらいとされるため、上司や社外の人には「お疲れ様です」を使うのが無難です。", "domain": "敬語"},
    {"q": "「了解しました」は上司に使ってもいい？", "a": "失礼ではないという見方もありますが、ビジネスでは「承知しました」「かしこまりました」の方が丁寧で安全です。", "domain": "敬語"},
    {"q": "関西弁の「なんでやねん」はどんな場面で使う？", "a": "相手のボケや意外な発言に対するツッコミです。本気で理由を聞いているわけではなく、会話のテンポを作る役割があります。", "domain": "方言"},
    {"q": "「すみません」が感謝の意味になるのはどんなとき？", "a": "物を拾ってもらったときなど、相手に手間をかけさせた場面です。「ありがとう」に申し訳なさが混ざったニュアンスになります。", "domain": "語用論"},
    {"q": "メールの「ご確認のほどよろしくお願いいたします」は丁寧すぎる？", "a": "取引先向けなら適切です。社内の同僚なら「ご確認お願いします」程度で十分です。", "domain": "ビジネス文書"},
    {"q": "「全然大丈夫」は正しい日本語？", "a": "「全然」は否定と組むものという説は近代の規範意識で、明治期には肯定でも使われていました。現在の会話では自然な表現です。", "domain": "語法"},
    {"q": "「一応」をよく使うのはなぜ？", "a": "断定を和らげて、責任や押しつけがましさを避けるためです。日本語の会話でよく使われるぼかし表現の一つです。", "domain": "語用論"},
    {"q": "「〜させていただきます」の使いすぎはなぜ嫌われる？", "a": "本来は相手の許可や恩恵がある場面の表現で、関係のない場面で多用すると回りくどく聞こえるためです。", "domain": "敬語"},
]

i = 0
while True:
    rec = SAMPLES[i % len(SAMPLES)]
    rid = s.publish(rec, floor_usd=10, meta={"lang": "ja", "author": "human", "license": "commercial-ok"})
    print(f"送信: {rid}  {rec['q']}")
    i += 1
    time.sleep(3)
